def test_sha256_hashing():
    assert sha256_text("hello") == hashlib.sha256(b"hello").hexdigest()


def test_disclosure_locales():
    labeler = SgiLabeler()
    for locale in ("en", "fr", "de", "es"):
        text = labeler.get_disclosure_text(locale)
        assert text
        assert labeler.is_label_removable() is False
    labeled = labeler.label_output("Hello world", "text", locale="en")
    assert LABEL_MARKER in labeled["label"]["marker"]
    assert labeled["label"]["removable"] is False
    assert "AI-generated content" in labeled["labeled_output"]
    code = labeler.label_output("print(1)", "code")
    assert "Generated by AI" in code["labeled_output"]


def test_generation_log_append_only_and_report(tmp_path: Path):
    store = GenerationLogStore(sqlite_path=tmp_path / "gen.db")
    row = store.log_generation(
        input_payload="prompt",
        output_payload="answer",
        model_name="test-model",
        user_id="u1",
        content_type="text",
        feature_endpoint="chat",
        session_id="s1",
    )
    assert row["input_hash"] == sha256_text("prompt")
    assert row["output_hash"] == sha256_text("answer")
    with pytest.raises(ImmutableLogError):
        store.update_entry(row["log_id"])
    with pytest.raises(ImmutableLogError):
        store.delete_entry(row["log_id"])

    day = row["timestamp"][:10]
    report = store.generate_compliance_report(day)
    assert report["entry_count"] == 1
    assert report["entries"][0]["log_id"] == row["log_id"]
    assert report["signature"]["value"]
    assert report["content_hash"]


