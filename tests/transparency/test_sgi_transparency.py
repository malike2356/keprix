def test_consent_granular_and_withdrawal(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setenv("KEPRIX_AI_CONSENT_REQUIRED", "1")
    gate = ConsentGate(base_dir=tmp_path)
    with pytest.raises(ConsentRequiredError):
        gate.require_consent("u1", "text_generation")
    with pytest.raises(ValueError):
        gate.record_consent("u1", "text_generation", action="granted", affirmative=False)

    gate.record_consent("u1", "text_generation", action="granted", affirmative=True)
    assert gate.require_consent("u1", "text_generation")["ok"] is True
    # Image consent is separate
    with pytest.raises(ConsentRequiredError):
        gate.require_consent("u1", "image_generation")

    gate.record_consent("u1", "text_generation", action="withdrawn", affirmative=True)
    with pytest.raises(ConsentRequiredError):
        gate.require_consent("u1", "text_generation")
    history = gate.get_consent_status("u1")["history"]
    assert len(history) == 2
    assert history[-1]["action"] == "withdrawn"
    with pytest.raises(RuntimeError):
        gate.delete_consent("u1", "text_generation")


def test_integration_consent_log_label(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setenv("KEPRIX_AI_CONSENT_REQUIRED", "1")
    monkeypatch.setenv("KEPRIX_AI_GENERATION_LOG_ENABLED", "1")
    monkeypatch.setenv("KEPRIX_AI_LABELING_ENABLED", "1")
    gate = ConsentGate(base_dir=tmp_path / "consent")
    store = GenerationLogStore(sqlite_path=tmp_path / "gen.db")

    # Patch singletons used by pipeline
    monkeypatch.setattr("keprix.transparency.pipeline.get_consent_gate", lambda: gate)
    monkeypatch.setattr("keprix.transparency.pipeline.get_generation_log_store", lambda: store)

    with pytest.raises(ConsentRequiredError):
        finalize_ai_output(
            input_payload="hi",
            output_payload="there",
            model_name="m1",
            user_id="u9",
        )

    gate.record_consent("u9", "text_generation", action="granted", affirmative=True)
    result = finalize_ai_output(
        input_payload="hi",
        output_payload="there",
        model_name="m1",
        user_id="u9",
        feature_endpoint="chat",
    )
    assert result["log"]["input_hash"] == sha256_text("hi")
    assert "AI-generated content" in result["labeled_output"]
    assert result["label"]["removable"] is False
    day = result["log"]["timestamp"][:10]
    report = store.generate_compliance_report(day)
    assert report["entry_count"] >= 1


