def build_aiva_wrapper_nodes(carina_nodes: dict[str, CapabilityNode]) -> dict[str, CapabilityNode]:
    """Aiva reuses Carina node implementations; metadata product=aiva only."""
    wrapped: dict[str, CapabilityNode] = {}
    for key, node in carina_nodes.items():
        if node.carina_admin_only:
            continue
        wrapped[key] = CapabilityNode(
            key=node.key,
            version=node.version,
            title=node.title,
            product="aiva",
            domain=node.domain,
            risk=node.risk,
            status=node.status,
            required_grants=node.required_grants,
            entitlements=node.entitlements or ("aiva.worker",),
            soft_wall=node.soft_wall,
            sync=node.sync,
            input_schema=node.input_schema,
            output_schema=node.output_schema,
            timeout_seconds=node.timeout_seconds,
            budget_units=node.budget_units,
            idempotent=node.idempotent,
            operator_guidance=node.operator_guidance,
            aiva_sku_ok=node.aiva_sku_ok,
            carina_admin_only=False,
        )
    return wrapped
