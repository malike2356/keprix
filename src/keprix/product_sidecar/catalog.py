"""Carina/Aiva capability node catalog (P0-P2 + owner-gated Nice)."""

from __future__ import annotations

from keprix.product_sidecar.types import CapabilityNode, NodeStatus, RiskClass


def _node(
    key: str,
    *,
    title: str,
    domain: str,
    risk: RiskClass,
    status: NodeStatus,
    soft_wall: bool = False,
    grants: tuple[str, ...] = (),
    entitlements: tuple[str, ...] = (),
    sync: bool = True,
    idempotent: bool = False,
    aiva_sku_ok: bool = True,
    carina_admin_only: bool = False,
    guidance: str = "",
    product: str = "carina",
) -> CapabilityNode:
    return CapabilityNode(
        key=key,
        version="1.0.0",
        title=title,
        product=product,
        domain=domain,
        risk=risk,
        status=status,
        required_grants=grants or (f"node:{key}",),
        entitlements=entitlements,
        soft_wall=soft_wall,
        sync=sync,
        input_schema={"type": "object"},
        output_schema={"type": "object"},
        timeout_seconds=60 if not sync else 30,
        budget_units=2 if risk in {RiskClass.OUTBOUND, RiskClass.MUTATE} else 1,
        idempotent=idempotent,
        operator_guidance=guidance,
        aiva_sku_ok=aiva_sku_ok,
        carina_admin_only=carina_admin_only,
    )


